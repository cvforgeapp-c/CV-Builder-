def validate_translations():
    english_keys = set(TRANSLATIONS["English (US / UK)"])
    issues = {}

    for language in SUPPORTED_LANGUAGES:
        language_dict = TRANSLATIONS.get(language)

        if not isinstance(language_dict, dict):
            issues[language] = {
                "missing": sorted(english_keys),
                "extra": [],
                "invalid_values": [],
            }
            continue

        language_keys = set(language_dict)
        missing = sorted(english_keys - language_keys)
        extra = sorted(language_keys - english_keys)
        invalid_values = sorted(
            key for key, value in language_dict.items()
            if not isinstance(value, str)
        )

        if missing or extra or invalid_values:
            issues[language] = {
                "missing": missing,
                "extra": extra,
                "invalid_values": invalid_values,
            }

    return issues


